@login_required
def report_download(request, pk):
    """Download report file"""
    report = get_object_or_404(Report, pk=pk, user=request.user)
    
    if not report.file:
        messages.error(request, 'No file available for download.')
        return redirect('reports:detail', pk=pk)
    
    report_logger.info(
        "Report %s downloaded by %s (format=%s)",
        report.pk, request.user.username, report.file_format,
    )

    # Serve file
    if report.file_format == 'csv':
        content_type = 'text/csv'
    elif report.file_format == 'json':
        content_type = 'application/json'
    elif report.file_format == 'pdf':
        content_type = 'application/pdf'
    else:
        content_type = 'application/octet-stream'
    
    with open(report.file.path, 'rb') as f:
        response = HttpResponse(f.read(), content_type=content_type)
        response['Content-Disposition'] = f'attachment; filename="{report.file.name.split("/")[-1]}"'
        return response

